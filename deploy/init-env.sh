#!/usr/bin/env bash
# Creates deploy/.env with fresh secrets. Run once on the server (deploy.sh does it for you).
#   deploy/init-env.sh                     # serve on the server's public IP over HTTP
#   deploy/init-env.sh app.example.com     # serve on a domain with automatic HTTPS
# Never regenerate secrets on a live install: BETTER_AUTH_SECRET protects the OAuth signing keys and
# ENCRYPTION_KEY protects stored site tokens and AI keys.
set -euo pipefail
cd "$(dirname "$0")"

if [[ -f .env ]]; then
  echo "deploy/.env already exists; leaving it unchanged." >&2
  exit 0
fi

domain="${1:-}"
if [[ -n "$domain" ]]; then
  site_address="$domain"
  origin="https://$domain"
else
  ip=$(curl -fsS --max-time 5 https://api.ipify.org || hostname -I | awk '{print $1}')
  site_address=":80"
  origin="http://$ip"
fi

secret() { openssl rand -base64 32 | tr -d '\n'; }

umask 077
cat > .env <<EOF
# Generated by deploy/init-env.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Keep this file private.

# Public address. To move to a domain later: point its DNS A record at this server, then set
# SITE_ADDRESS=app.example.com and WEB_ORIGIN=https://app.example.com and run deploy again.
SITE_ADDRESS=$site_address
WEB_ORIGIN=$origin

POSTGRES_PASSWORD=$(openssl rand -hex 24)
BETTER_AUTH_SECRET=$(secret)
ENCRYPTION_KEY=$(secret)

# AI. Workspaces can also add their own keys in Settings → AI keys.
ANTHROPIC_API_KEY=
OPENAI_API_KEY=
# false = workspaces must bring their own keys.
ALLOW_PLATFORM_KEYS=true
AI_FAKE=false

# Email: none = password reset links and invitations are written to the API log
# (docker compose -f deploy/docker-compose.yml logs api). Set resend + RESEND_API_KEY to send them.
EMAIL_PROVIDER=none
RESEND_API_KEY=
EMAIL_FROM=TriCity Writer <no-reply@${domain:-example.com}>
EOF
echo "Created deploy/.env for $origin"
